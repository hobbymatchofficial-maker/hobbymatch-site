// Builds reviews.html ("What our users say") from data/reviews.json.
//   node scripts/build-reviews.mjs            write reviews.html
//   node scripts/build-reviews.mjs --check    exit 1 if reviews.html is out of date
//
// Only genuine reviews copied exactly from the App Store, Google Play or
// Trustpilot belong in the data file: see data/README.md. This script
// checks the shape of each entry; it can't check that a review is real.
// No dependencies.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCES = {
  'App Store': /^https:\/\/apps\.apple\.com\//,
  'Google Play': /^https:\/\/play\.google\.com\//,
  'Trustpilot': /^https:\/\/([a-z]{2}\.)?trustpilot\.com\//,
};

export function escapeHtml(s) {
  return String(s ?? '').replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]);
}

export function validate(list, today = new Date().toISOString().slice(0, 10)) {
  if (!Array.isArray(list)) throw new Error('data/reviews.json must be a list ([...])');
  const known = new Set(['name', 'date', 'rating', 'source', 'url', 'title', 'text']);
  list.forEach((r, i) => {
    const at = `review ${i + 1}`;
    if (!r || typeof r !== 'object') throw new Error(`${at}: not an object`);
    for (const k of Object.keys(r)) if (!known.has(k)) throw new Error(`${at}: unknown field "${k}"`);
    if (typeof r.name !== 'string' || !r.name.trim() || r.name.length > 60) throw new Error(`${at}: name (first name or handle) is required`);
    if (!/^\d{4}-\d{2}-\d{2}$/.test(r.date || '') || isNaN(new Date(r.date))) throw new Error(`${at}: date must be YYYY-MM-DD`);
    if (r.date > today) throw new Error(`${at}: date is in the future`);
    if (!Number.isInteger(r.rating) || r.rating < 1 || r.rating > 5) throw new Error(`${at}: rating must be a whole number from 1 to 5`);
    if (!SOURCES[r.source]) throw new Error(`${at}: source must be one of ${Object.keys(SOURCES).join(', ')}`);
    if (typeof r.url !== 'string' || !SOURCES[r.source].test(r.url)) throw new Error(`${at}: url must be a link to the review on ${r.source}`);
    for (const k of ['title', 'text']) if (r[k] != null && typeof r[k] !== 'string') throw new Error(`${at}: ${k} must be text`);
  });
  return [...list].sort((a, b) => (a.date < b.date ? 1 : a.date > b.date ? -1 : 0));
}

const longDate = d => new Date(`${d}T12:00:00Z`).toLocaleDateString('en-GB', { day: 'numeric', month: 'long', year: 'numeric', timeZone: 'UTC' });

export function reviewItem(r) {
  const stars = '★'.repeat(r.rating) + '☆'.repeat(5 - r.rating);
  return `        <li>
          <article>
            <p class="stars" aria-label="${r.rating} out of 5 stars">${stars}</p>
            <blockquote cite="${escapeHtml(r.url)}">
${r.title ? `              <p><strong>${escapeHtml(r.title)}</strong></p>\n` : ''}${r.text ? `              <p>${escapeHtml(r.text)}</p>\n` : ''}            </blockquote>
            <footer>${escapeHtml(r.name)}, <time datetime="${r.date}">${longDate(r.date)}</time>, on <a href="${escapeHtml(r.url)}" rel="nofollow noopener">${escapeHtml(r.source)}</a></footer>
          </article>
        </li>`;
}

