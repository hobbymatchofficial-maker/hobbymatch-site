if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const list = validate(JSON.parse(readFileSync(join(root, 'data/reviews.json'), 'utf8')));
  const html = render(list);
  const out = join(root, 'reviews.html');
  if (process.argv.includes('--check')) {
    let current = '';
    try { current = readFileSync(out, 'utf8'); } catch {}
    if (current !== html) { console.error('reviews.html is out of date: run node scripts/build-reviews.mjs'); process.exit(1); }
    console.log(`reviews.html is up to date (${list.length} reviews)`);
  } else {
    writeFileSync(out, html);
    console.log(`Wrote reviews.html (${list.length} reviews)`);
  }
}
